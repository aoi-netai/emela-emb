//! Source-aware typed IR, before backend normalization. IDs refer to resolved definitions.
use super::{
    ast::{Binary, Unary},
    types::{Signature, ValueType},
};
use crate::{Span, sources::Intrinsic};
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub(crate) struct DefinitionId(pub usize);
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub(crate) struct LocalId(pub usize);
#[derive(Clone, Debug)]
pub(crate) struct Local {
    pub id: LocalId,
    pub name: String,
    pub ty: ValueType,
}
#[derive(Clone, Debug)]
pub(crate) struct Function {
    pub id: DefinitionId,
    pub type_parameters: usize,
    /// A synchronous operation implementation keeps a synchronous ABI after its body is checked.
    pub immediate: bool,
    pub constant: bool,
    pub origin: Option<DefinitionId>,
    /// Typed getters in one shared const family point to its erased canonical getter.
    pub canonical_const: Option<DefinitionId>,
    pub derivation: Option<super::traits::BuiltinTrait>,
    /// Concrete error display entry; its parameter retains generic error arguments.
    pub error_show: Option<crate::contract::ir::EnumId>,
    pub name: String,
    pub source_name: String,
    pub span: Span,
    pub exported: bool,
    pub export_symbol: Option<String>,
    pub signature: Signature,
    pub params: Vec<Local>,
    pub external: Option<String>,
    pub intrinsic: Option<Intrinsic>,
    pub body: Option<Block>,
}
#[derive(Clone, Debug)]
pub(crate) struct Program {
    pub core: crate::contract::ir::Definitions,
    pub registry: super::traits::Registry,
    pub functions: Vec<Function>,
}
#[derive(Clone, Debug)]
pub(crate) struct Block {
    pub statements: Vec<Statement>,
    pub ty: ValueType,
    pub span: Span,
}
#[derive(Clone, Debug)]
pub(crate) enum Statement {
    Pattern { pattern: Pattern, value: Expr },
    Expr(Expr),
}
#[derive(Clone, Debug)]
pub(crate) struct Expr {
    pub kind: ExprKind,
    pub ty: ValueType,
    pub span: Span,
}
#[derive(Clone, Debug)]
pub(crate) enum ExprKind {
    /// Value of the current invocation's evidence table; generated by trusted lowering.
    Evidence,
    Literal(Literal),
    /// Lookup uses the current invocation's evidence, retaining the exact label key.
    Use {
        effect: crate::contract::ir::EffectId,
    },
    OpCall {
        handler: Box<Expr>,
        effect: crate::contract::ir::EffectId,
        op: usize,
        errors: Vec<crate::contract::ir::TypeId>,
        args: Vec<Expr>,
        order: Vec<usize>,
    },
    Handler {
        name: String,
        effect: crate::contract::ir::EffectId,
        operations: Vec<Expr>,
    },
    /// Extend evidence for this body without retiring the supplied capabilities.
    Provide {
        base: Option<Box<Expr>>,
        bindings: Vec<(crate::contract::ir::EffectId, Expr)>,
        body: Block,
    },
    With {
        bindings: Vec<WithBinding>,
        body: Block,
    },
    /// Trusted structured concurrency operation. Arguments preserve written order;
    /// concrete failure identities remain available before ABI projection.
    Fiber {
        op: crate::contract::ir::FiberOp,
        args: Vec<Expr>,
        errors: Vec<crate::contract::ir::TypeId>,
    },
    Concat(Vec<Expr>),
    Fail(Box<Expr>),
    Coerce(Box<Expr>),
    Escape {
        value: Box<Expr>,
        error: Local,
        arms: Vec<Arm>,
    },
    Tag(Box<Expr>),
    Builtin {
        op: crate::contract::ir::Builtin,
        args: Vec<Expr>,
    },
    TraitCall {
        trait_id: super::traits::TraitId,
        method: String,
        self_type: crate::contract::ir::TypeId,
        method_type_arguments: Vec<crate::contract::ir::TypeId>,
        args: Vec<Expr>,
        order: Vec<usize>,
        nested_show: bool,
    },
    Match {
        value: Box<Expr>,
        arms: Vec<Arm>,
    },
    Tuple(Vec<Expr>),
    List {
        elements: Vec<Expr>,
        tail: Option<Box<Expr>>,
    },
    Make {
        ctor: crate::contract::ir::CtorRef,
        args: Vec<Expr>,
        order: Vec<usize>,
    },
    Field {
        base: Box<Expr>,
        ctor: crate::contract::ir::CtorRef,
        index: usize,
    },
    Local(LocalId),
    FnRef {
        target: DefinitionId,
        type_arguments: Vec<crate::contract::ir::TypeId>,
    },
    Lambda {
        params: Vec<Local>,
        captures: Vec<LocalId>,
        body: Block,
    },
    Apply {
        callee: Box<Expr>,
        args: Vec<Expr>,
        order: Vec<usize>,
    },
    Unary {
        op: Unary,
        value: Box<Expr>,
    },
    Binary {
        op: Binary,
        left: Box<Expr>,
        right: Box<Expr>,
    },
    Call {
        target: DefinitionId,
        type_arguments: Vec<crate::contract::ir::TypeId>,
        args: Vec<Expr>,
        order: Vec<usize>,
    },
    If {
        condition: Box<Expr>,
        then: Block,
        else_: Block,
    },
    Block(Block),
    Assert(Box<Expr>),
}
/// Acquisition is sequential; cleanup protects only the successfully acquired suffix.
#[derive(Clone, Debug)]
pub(crate) struct WithBinding {
    pub local: Local,
    pub value: Expr,
    pub effects: Vec<crate::contract::ir::EffectId>,
    pub cleanup: Option<Expr>,
    pub retire: Option<String>,
}
#[derive(Clone, Debug)]
pub(crate) enum Literal {
    Int(i32),
    Int64(i64),
    Float(f64),
    String(String),
    Bool(bool),
    Unit,
}

#[derive(Clone, Debug)]
pub(crate) struct Pattern {
    pub kind: PatternKind,
    pub ty: ValueType,
    pub span: Span,
}
#[derive(Clone, Debug)]
pub(crate) enum PatternKind {
    Constant {
        value: Box<Expr>,
        coverage: Option<Box<Pattern>>,
        comparison: Option<ConstantEquality>,
    },
    Any,
    Bind(Local),
    Literal(Literal),
    Tuple(Vec<Pattern>),
    ListNil,
    ListCons {
        head: Box<Pattern>,
        tail: Box<Pattern>,
    },
    Constructor {
        ctor: crate::contract::ir::CtorRef,
        fields: Vec<Pattern>,
    },
}
#[derive(Clone, Debug)]
pub(crate) struct Arm {
    pub pattern: Pattern,
    pub guard: Option<Expr>,
    pub value: Expr,
}

#[derive(Clone, Debug)]
pub(crate) enum ConstantEquality {
    Function(DefinitionId),
    Structural(crate::contract::ir::TypeId),
}
